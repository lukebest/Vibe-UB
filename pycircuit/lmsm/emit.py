#!/usr/bin/env python3
"""Emit PRODUCT + HOOKS Verilog for ub_lmsm via compile() + pycc.

    python3 scripts/emit_rtl.py
    python3 pycircuit/lmsm/emit.py

PRODUCT  TEST_HOOKS=0  → rtl/lmsm/ub_lmsm.v
HOOKS    TEST_HOOKS=1  → rtl/lmsm/hooks/ub_lmsm.v

Do not put the repo root on PYTHONPATH (the toolchain package is also
named pycircuit). ``pycircuit/`` is the import root.
"""

from __future__ import annotations

import os
import shutil
import site
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PYC = HERE.parent
REPO = PYC.parent
RTL = REPO / "rtl"
PRODUCT_V = RTL / "lmsm" / "ub_lmsm.v"
HOOKS_V = RTL / "lmsm" / "hooks" / "ub_lmsm.v"

_repo_toolchain = REPO / ".pycircuit_out" / "toolchain" / "install"
os.environ.setdefault(
    "PYC_TOOLCHAIN_ROOT",
    str(_repo_toolchain if (_repo_toolchain / "bin" / "pycc").is_file()
        else "/tmp/pyCircuit/.pycircuit_out/toolchain/install"),
)
_root = Path(os.environ["PYC_TOOLCHAIN_ROOT"])
os.environ["PATH"] = f"{_root / 'bin'}:{os.environ.get('PATH', '')}"
_venv = Path(os.environ.get("UB_PYC_VENV", str(REPO / ".pycircuit-venv")))
if not (_venv / "bin" / "python").is_file():
    _venv = Path(os.environ.get("UB_PYC_VENV", "/tmp/venv"))
for _site in _venv.glob("lib/python*/site-packages"):
    site.addsitedir(str(_site))
if str(PYC) not in sys.path:
    sys.path.insert(0, str(PYC))

from lmsm.ub_lmsm import build  # noqa: E402

PYCC_EMIT = ["--emit=verilog"]
PYCC_LOGIC_DEPTH = "64"
_PRIMITIVES = (
    "pyc_reg",
    "pyc_add",
    "pyc_and",
    "pyc_or",
    "pyc_not",
    "pyc_xor",
    "pyc_mux",
    "pyc_fifo",
    "pyc_byte_mem",
    "pyc_sync_mem",
    "pyc_sync_mem_dp",
    "pyc_async_fifo",
    "pyc_cdc_sync",
)


def toolchain_root() -> Path:
    env = os.environ.get("PYC_TOOLCHAIN_ROOT")
    if env:
        return Path(env)
    return Path("/tmp/pyCircuit/.pycircuit_out/toolchain/install")


def pycc_bin() -> Path:
    root = toolchain_root()
    cand = root / "bin" / "pycc"
    if cand.is_file():
        return cand
    found = shutil.which("pycc")
    if found:
        return Path(found)
    raise FileNotFoundError(
        "pycc not found. Run scripts/gate/setup_pycircuit.sh "
        f"(expected {root / 'bin' / 'pycc'})"
    )


def keep_used_primitive_includes(verilog: str) -> str:
    used: set[str] = set()
    for name in _PRIMITIVES:
        if f"{name} #" in verilog or f"{name} " in verilog.replace(
            f'`include "{name}.v"', ""
        ):
            used.add(name)
    kept: list[str] = []
    for line in verilog.splitlines(keepends=True):
        stripped = line.strip()
        if stripped.startswith("`include"):
            if not any(f'"{name}.v"' in stripped for name in used):
                continue
        kept.append(line)
    return "".join(kept)


def compile_to_verilog(*, test_hooks: bool) -> str:
    from pycircuit import compile as pyc_compile

    design = pyc_compile(build, name="ub_lmsm", test_hooks=1 if test_hooks else 0)
    mlir = design.emit_mlir()
    pycc = pycc_bin()
    env = os.environ.copy()
    env.setdefault("PYC_TOOLCHAIN_ROOT", str(toolchain_root()))
    env["PATH"] = f"{toolchain_root() / 'bin'}:{env.get('PATH', '')}"
    with tempfile.TemporaryDirectory(prefix="ub-pycc-") as td:
        mlir_path = Path(td) / "ub_lmsm.pyc"
        v_path = Path(td) / "ub_lmsm.v"
        mlir_path.write_text(mlir, encoding="utf-8")
        cmd = [
            str(pycc),
            str(mlir_path),
            *PYCC_EMIT,
            f"--logic-depth={PYCC_LOGIC_DEPTH}",
            "-o",
            str(v_path),
        ]
        subprocess.check_call(cmd, env=env)
        body = keep_used_primitive_includes(v_path.read_text(encoding="utf-8"))
    th = 1 if test_hooks else 0
    header = (
        "// GENERATED by pycc from pycircuit — do not edit.\n"
        "// Reproduce: python3 scripts/emit_rtl.py\n"
        "// compile() + pycc --emit=verilog --logic-depth=64\n"
        f"// TEST_HOOKS={th}\n"
    )
    return header + body


def generate() -> list[Path]:
    product = compile_to_verilog(test_hooks=False)
    hooks = compile_to_verilog(test_hooks=True)
    for token in (
        "tb_test_mode",
        "tb_obs_link_ready",
        "tb_obs_link_up",
        "tb_obs_lmsm_st",
        "tb_inj_am_lock",
        "tb_inj_lid_bad",
    ):
        if any(
            line.lstrip().startswith(("input", "output")) and token in line
            for line in product.splitlines()
        ):
            raise RuntimeError(f"PRODUCT netlist must not contain {token}")
    if "`ifdef" in product or "`ifdef" in hooks:
        raise RuntimeError("generated Verilog must not use ifdef TEST_HOOKS")
    PRODUCT_V.parent.mkdir(parents=True, exist_ok=True)
    HOOKS_V.parent.mkdir(parents=True, exist_ok=True)
    PRODUCT_V.write_text(product, encoding="utf-8")
    HOOKS_V.write_text(hooks, encoding="utf-8")
    return [PRODUCT_V, HOOKS_V]


def main() -> int:
    paths = generate()
    for path in paths:
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

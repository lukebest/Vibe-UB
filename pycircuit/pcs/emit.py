#!/usr/bin/env python3
"""Emit PRODUCT + HOOKS for the PCS leaves in this PR.

Name is emit.py so gatelib leaf discovery skips it (not a leaf).
Does not add scripts/emit_rtl.py (other PRs own that entry). Same pycc
flags as gen_private_stub / PR #5: --emit=verilog --logic-depth=64.
SPEC §10 has no hook ports on these leaves, so HOOKS == PRODUCT ports.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
RTL = REPO / "rtl"


def _toolchain_root() -> Path:
    env = os.environ.get("PYC_TOOLCHAIN_ROOT")
    if env:
        return Path(env)
    for cand in (
        REPO / ".pycircuit_out" / "toolchain" / "install",
        Path("/tmp/pyCircuit/.pycircuit_out/toolchain/install"),
    ):
        if (cand / "bin" / "pycc").is_file():
            return cand
    return REPO / ".pycircuit_out" / "toolchain" / "install"


def _pycc() -> Path:
    root = _toolchain_root()
    cand = root / "bin" / "pycc"
    if cand.is_file():
        return cand
    found = shutil.which("pycc")
    if found:
        return Path(found)
    raise FileNotFoundError(
        "pycc not found. Run scripts/gate/setup_pycircuit.sh "
        f"(expected {root / 'bin' / 'pycc'})"
    )


_PRIMITIVES = (
    "pyc_reg",
    "pyc_add",
    "pyc_and",
    "pyc_or",
    "pyc_not",
    "pyc_xor",
    "pyc_mux",
    "pyc_fifo",
    "pyc_byte_mem",
    "pyc_sync_mem",
    "pyc_sync_mem_dp",
    "pyc_async_fifo",
    "pyc_cdc_sync",
)


def _keep_used_includes(verilog: str) -> str:
    used: set[str] = set()
    for name in _PRIMITIVES:
        rest = verilog.replace(f'`include "{name}.v"', "")
        if f"{name} #" in verilog or f"{name} " in rest:
            used.add(name)
    kept: list[str] = []
    for line in verilog.splitlines(keepends=True):
        stripped = line.strip()
        if stripped.startswith("`include"):
            if not any(f'"{name}.v"' in stripped for name in used):
                continue
        kept.append(line)
    return "".join(kept)


def _compile(build, name: str, params: dict, test_hooks: bool) -> str:
    from pycircuit import compile as pyc_compile

    kw = dict(params)
    import inspect

    sig = inspect.signature(build)
    if "test_hooks" in sig.parameters:
        kw["test_hooks"] = 1 if test_hooks else 0
    design = pyc_compile(build, name=name, **kw)
    mlir = design.emit_mlir()
    pycc = _pycc()
    env = os.environ.copy()
    env.setdefault("PYC_TOOLCHAIN_ROOT", str(_toolchain_root()))
    env["PATH"] = f"{_toolchain_root() / 'bin'}:{env.get('PATH', '')}"
    with tempfile.TemporaryDirectory(prefix="ub-pcs-pycc-") as td:
        mlir_path = Path(td) / f"{name}.pyc"
        v_path = Path(td) / f"{name}.v"
        mlir_path.write_text(mlir, encoding="utf-8")
        subprocess.check_call(
            [
                str(pycc),
                str(mlir_path),
                "--emit=verilog",
                "--logic-depth=64",
                "-o",
                str(v_path),
            ],
            env=env,
        )
        body = _keep_used_includes(v_path.read_text(encoding="utf-8"))
    th = 1 if test_hooks else 0
    header = (
        "// GENERATED by pycc from pycircuit — do not edit.\n"
        "// Reproduce: PYTHONPATH=pycircuit python3 -P pycircuit/pcs/emit.py\n"
        "// compile() + pycc --emit=verilog --logic-depth=64\n"
        f"// TEST_HOOKS={th}\n"
    )
    return header + body


def emit_stub(out_root: Path = RTL) -> list[Path]:
    """Write GATE-PRIV-002 path and the inventory-visible layer-dir copy.

    discover_rtl only scans rtl/<layer>/*.{v,sv}, so the layer-dir copy
    lets lint/synth close ub_pcs_amctl_rx over the public stub.
    """
    from pcs.stub.ub_pcs_amctl_cw_dec import build as stub_build

    sys.path.insert(0, str(REPO / "scripts" / "gate"))
    from contract_hash import contract_sha256

    digest = contract_sha256(
        REPO / "docs" / "arch" / "pcs" / "contracts" / "ub_pcs_amctl_cw_dec.md"
    )
    body = _compile(stub_build, "ub_pcs_amctl_cw_dec", {}, False)
    # Drop the TEST_HOOKS header; stub uses the contract hash header.
    if body.startswith("// GENERATED"):
        body = "\n".join(body.splitlines()[4:]) + "\n"
    header = (
        f"// contract_sha256: {digest}\n"
        "// generated-by: scripts/gate/gen_private_stub.py\n"
    )
    text = header + body
    dests = [
        out_root / "pcs" / "stub" / "ub_pcs_amctl_cw_dec.v",
        out_root / "pcs" / "ub_pcs_amctl_cw_dec.v",
    ]
    written: list[Path] = []
    for dest in dests:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding="utf-8")
        written.append(dest)
    return written


def _strip_stub_module(verilog: str, name: str) -> str:
    """Drop the stub body; keep named instances in the parent (PR #48)."""
    needle = f"module {name} ("
    start = verilog.find(needle)
    if start < 0:
        needle = f"module {name}("
        start = verilog.find(needle)
    if start < 0:
        return verilog
    comm = verilog.rfind("// Generated by pycc", 0, start)
    prev_end = verilog.rfind("endmodule", 0, start)
    if comm >= 0 and comm > prev_end:
        start = comm
    end = verilog.find("endmodule", start)
    if end < 0:
        raise SystemExit(f"no endmodule for stub {name}")
    end = end + len("endmodule")
    while end < len(verilog) and verilog[end] in "\r\n":
        end += 1
    return verilog[:start] + verilog[end:]


def emit_all(out_root: Path = RTL) -> list[Path]:
    # Import after PYTHONPATH has pycircuit/.
    from pcs import ub_pcs_amctl_rx as amctl_rx
    from pcs import ub_pcs_nullblk_det as nullblk

    written: list[Path] = list(emit_stub(out_root))
    leaves = (
        (nullblk.LEAF, nullblk.build, {}),
        (amctl_rx.LEAF, amctl_rx.build, {}),
    )
    for name, build, params in leaves:
        product = out_root / "pcs" / f"{name}.v"
        hooks = out_root / "pcs" / "hooks" / f"{name}.v"
        product.parent.mkdir(parents=True, exist_ok=True)
        hooks.parent.mkdir(parents=True, exist_ok=True)
        prod_txt = _compile(build, name, params, False)
        hooks_txt = _compile(build, name, params, True)
        if name != "ub_pcs_amctl_cw_dec":
            prod_txt = _strip_stub_module(prod_txt, "ub_pcs_amctl_cw_dec")
            hooks_txt = _strip_stub_module(hooks_txt, "ub_pcs_amctl_cw_dec")
        product.write_text(prod_txt, encoding="utf-8")
        hooks.write_text(hooks_txt, encoding="utf-8")
        written.extend([product, hooks])
    return written


def main() -> int:
    if str(HERE.parent) not in sys.path:
        sys.path.insert(0, str(HERE.parent))
    paths = emit_all()
    for path in paths:
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

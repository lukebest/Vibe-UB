def is_cmn_mem_module(name: str) -> bool:
    return name == CMN_MEM_CELL or name.startswith(CMN_MEM_CELL + "_")


# Xia: ub_cmn_mem_1r1w_<tag> with tag d<DEPTH>w<WIDTH>[m<WMASK_W>]
# e.g. d512w512m64, d64w64m16. Bits for the blackbox test are DEPTH*WIDTH.
_CMN_MEM_TAG_RE = re.compile(r"^d(\d+)w(\d+)(?:m(\d+))?$", re.I)


def parse_cmn_mem_tag(tag: str | None) -> dict[str, int] | None:
    if not tag:
        return None
    m = _CMN_MEM_TAG_RE.fullmatch(str(tag).strip().lstrip("_"))
    if not m:
        return None
    out = {"DEPTH": int(m.group(1)), "WIDTH": int(m.group(2))}
    if m.group(3):
        out["WMASK_W"] = int(m.group(3))
    return out


def cmn_mem_tag_of(name: str) -> str | None:
    """Return the d<DEPTH>w<WIDTH>[m<WMASK_W>] tag, or None."""
    if name == CMN_MEM_CELL:
        return None
    prefix = CMN_MEM_CELL + "_"
    if name.startswith(prefix):
        tag = name[len(prefix) :]
        if parse_cmn_mem_tag(tag):
            return tag
    return None


_CMN_THRESH_CACHE: int | None = None


def read_cmn_mem_threshold_bits() -> int:
    """Threshold in bits. Read impl_quick_synth.md; default 4096 (4 kbit)."""
    global _CMN_THRESH_CACHE
    if _CMN_THRESH_CACHE is not None:
        return _CMN_THRESH_CACHE
    path = IMPL_QUICK_SYNTH_MD
    if not path.is_file():
        print(
            f"NOTE: {rel(path)} missing; "
            f"ub_cmn_mem_1r1w blackbox threshold={DEFAULT_CMN_MEM_THRESH_BITS} bits"
        )
        _CMN_THRESH_CACHE = DEFAULT_CMN_MEM_THRESH_BITS
        return _CMN_THRESH_CACHE
    text = path.read_text(encoding="utf-8", errors="replace")
    m = re.search(
        r"(?:threshold|blackbox|cmn_mem)[^\n]{0,60}?(\d+)\s*bits?",
        text,
        re.I,
    )
    if m:
        _CMN_THRESH_CACHE = int(m.group(1))
        return _CMN_THRESH_CACHE
    m = re.search(r"(\d+(?:\.\d+)?)\s*kbit", text, re.I)
    if m:
        _CMN_THRESH_CACHE = int(float(m.group(1)) * 1024)
        return _CMN_THRESH_CACHE
    m = re.search(r"\b(2048|4096|8192|16384)\b", text)
    if m:
        _CMN_THRESH_CACHE = int(m.group(1))
        return _CMN_THRESH_CACHE
    print(
        f"NOTE: {rel(path)} has no kbit/bits threshold; "
        f"using {DEFAULT_CMN_MEM_THRESH_BITS}"
    )
    _CMN_THRESH_CACHE = DEFAULT_CMN_MEM_THRESH_BITS
    return _CMN_THRESH_CACHE


def _parse_int_lit(text: str) -> int | None:
    text = text.strip().replace("_", "")
    if re.fullmatch(r"\d+", text):
        return int(text)
    m = re.fullmatch(r"(\d+)'[dD](\d+)", text)
    if m:
        return int(m.group(2))
    m = re.fullmatch(r"(\d+)'[hH]([0-9a-fA-F]+)", text)
    if m:
        return int(m.group(2), 16)
    return None


def parse_cmn_mem_dims(path: Path | None, extra: dict[str, Any] | None = None) -> tuple[int | None, int | None]:
    """Return (depth, width) from tag / params / file. Bits = DEPTH*WIDTH."""
    depth = width = None
    extra = extra or {}
    for key in (
        extra.get("tag"),
        extra.get("module"),
        path.stem if path is not None else None,
    ):
        if not key:
            continue
        tag = cmn_mem_tag_of(str(key)) or (
            str(key) if parse_cmn_mem_tag(str(key)) else None
        )
        parsed = parse_cmn_mem_tag(tag)
        if parsed:
            depth = depth or parsed["DEPTH"]
            width = width or parsed["WIDTH"]
            break
    for key, val in extra.items():
        lk = str(key).lower()
        if lk in {"depth", "words", "entries"} and isinstance(val, (int, str)):
            parsed = _parse_int_lit(str(val))
            if parsed is not None:
                depth = parsed
        if lk in {"width", "dw", "data_w"} and isinstance(val, (int, str)):
            parsed = _parse_int_lit(str(val))
            if parsed is not None:
                width = parsed
    if path and path.is_file():
        text = strip_verilog_comments(path.read_text(encoding="utf-8", errors="replace"))
        for name, dest in (("depth", "depth"), ("width", "width"), ("dw", "width")):
            m = re.search(
                rf"\b(?:parameter|localparam)\s+(?:integer\s+)?{name}\s*=\s*([^,;]+)",
                text,
                re.I,
            )
            if m:
                parsed = _parse_int_lit(m.group(1))
                if parsed is not None:
                    if dest == "depth" and depth is None:
                        depth = parsed
                    if dest == "width" and width is None:
                        width = parsed
        # array:  reg [W-1:0] mem [0:D-1]
        m = re.search(
            r"\b(?:reg|logic)\s*\[\s*(\d+)\s*[-:]",
            text,
            re.I,
        )
        m2 = re.search(
            r"\]\s*[A-Za-z_][A-Za-z0-9_]*\s*\[\s*(?:0\s*:\s*)?(\d+)",
            text,
        )
        if width is None and m:
            width = int(m.group(1)) + 1
        if depth is None and m2:
            depth = int(m2.group(1)) + (0 if "0:" in (m2.group(0) or "") else 0)
            if "0:" in m2.group(0):
                depth = int(m2.group(1)) + 1
        # filename / module: official d<DEPTH>w<WIDTH>[m<WMASK_W>]; legacy _NxN / _dN_wN
        stem = path.stem
        parsed = parse_cmn_mem_tag(cmn_mem_tag_of(stem) or "")
        if parsed:
            depth = depth or parsed["DEPTH"]
            width = width or parsed["WIDTH"]
        m = re.search(r"_(\d+)x(\d+)$", stem, re.I)
        if m:
            depth = depth or int(m.group(1))
            width = width or int(m.group(2))
        m = re.search(r"_d(\d+)_w(\d+)", stem, re.I)
        if m:
            depth = depth or int(m.group(1))
            width = width or int(m.group(2))
    return depth, width


def cmn_mem_bits(path: Path | None, extra: dict[str, Any] | None = None) -> int | None:
    depth, width = parse_cmn_mem_dims(path, extra)
    if depth is None or width is None:
        return None
    return depth * width


def cmn_mem_is_large(path: Path | None, extra: dict[str, Any] | None = None, thresh: int | None = None) -> bool:
    bits = cmn_mem_bits(path, extra)
    if bits is None:
        return False
    return bits > (thresh if thresh is not None else read_cmn_mem_threshold_bits())


def large_cmn_mem_lib_files(top: str, disc: dict[str, Any] | None = None) -> list[Path]:
    """Mem files that parent synth/equiv must read with -lib (same copy both sides)."""
    thresh = read_cmn_mem_threshold_bits()
    disc = disc or discover_rtl()
    defined: dict = disc.get("defined") or {}
    files: list[Path] = []
    seen: set[Path] = set()
    # Walk the instance closure.
    stack = [top]
    visited: set[str] = set()
    inst_map: dict[str, set[str]] = disc.get("instantiations") or {}
    while stack:
        name = stack.pop()
        if name in visited:
            continue
        visited.add(name)
        unit = defined.get(name)
        if unit is None:
            continue
        if is_cmn_mem_module(name) and cmn_mem_is_large(unit.file, thresh=thresh):
            rp = unit.file.resolve()
            if rp not in seen:
                seen.add(rp)
                files.append(unit.file)
            continue
        # Instance-level overrides on this parent.
        if unit.file.is_file() and not is_cmn_mem_module(name):
            text = strip_verilog_comments(
                unit.file.read_text(encoding="utf-8", errors="replace")
            )
            for m in re.finditer(
                rf"\b({re.escape(CMN_MEM_CELL)}\w*)\s+(?:#\s*\((.*?)\)\s*)?"
                rf"([A-Za-z_][A-Za-z0-9_]*)\s*\(",
                text,
                re.S,
            ):
                cell, plist, _inst = m.group(1), m.group(2) or "", m.group(3)
                params: dict[str, Any] = {}
                tagged = parse_cmn_mem_tag(cmn_mem_tag_of(cell) or "")
                if tagged:
                    params.update(tagged)
                for pm in re.finditer(
                    r"\.(DEPTH|WIDTH|WMASK_W|depth|width|wmask_w)\s*\(\s*([^)]+)\)",
                    plist,
                    re.I,
                ):
                    params[pm.group(1)] = pm.group(2).strip()
                cell_unit = defined.get(cell)
                cell_path = cell_unit.file if cell_unit is not None else None
                if cmn_mem_is_large(cell_path, params, thresh=thresh) and cell_path:
                    rp = cell_path.resolve()
                    if rp not in seen:
                        seen.add(rp)
                        files.append(cell_path)
        for child in inst_map.get(name, set()):
            stack.append(child)
    return files


def placeholder_mark_present(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    return PLACEHOLDER_MARK in text


def collect_placeholder_policy_findings(check: str = "emit") -> list[Finding]:
    """_placeholder must not be instantiated by PRODUCT; source needs a mark."""
    findings: list[Finding] = []
    disc = discover_rtl()
    inst_map: dict[str, set[str]] = disc.get("instantiations") or {}
    defined: dict[str, RtlUnit] = disc.get("defined") or {}
    for parent, children in inst_map.items():
        unit = defined.get(parent)
        if unit is None:
            continue
        if is_placeholder_path(unit.file) or is_hooks_path(unit.file):
            continue
        for child in sorted(children):
            if not is_placeholder_module(child):
                continue
            findings.append(
                Finding(
                    check=check,
                    module=parent,
                    file=rel(unit.file),
                    rule="PLACEHOLDER_INSTANTIATED",
                    message=(
                        f"PRODUCT netlist instantiates placeholder cell {child}; "
                        f"_placeholder is lint/TB only (SPEC §2.2)"
                    ),
                )
            )
    seen_src: set[str] = set()
    for leaf in discover_pycircuit_leaves():
        if not leaf.get("placeholder"):
            continue
        src = REPO_ROOT / leaf["source"]
        key = rel(src)
        if key in seen_src:
            continue
        seen_src.add(key)
        if src.is_file() and not placeholder_mark_present(src):
            findings.append(
                Finding(
                    check=check,
                    module=leaf["module"],
                    file=key,
                    rule="PLACEHOLDER_SOURCE_MISSING",
                    message=(
                        "placeholder source must name its origin "
                        f"(constant or comment {PLACEHOLDER_MARK})"
                    ),
                )
            )
    for leaf in discover_product_leaves():
        if not leaf.get("placeholder"):
            continue
        prod = REPO_ROOT / leaf["product"]
        src = None
        for pyc in discover_pycircuit_leaves():
            if pyc.get("module") == leaf["module"] or pyc.get("leaf") == leaf.get("leaf"):
                if pyc.get("placeholder"):
                    src = REPO_ROOT / pyc["source"]
                    break
        if src and src.is_file():
            continue
        if prod.is_file() and not placeholder_mark_present(prod):
            findings.append(
                Finding(
                    check=check,
                    module=leaf["module"],
                    file=rel(prod),
                    rule="PLACEHOLDER_SOURCE_MISSING",
                    message=(
                        "placeholder netlist has no pycircuit source mark; "
                        f"add {PLACEHOLDER_MARK} in the source (or this file)"
                    ),
                )
            )
    return findings


def discover_leaf_pairs() -> list[dict[str, str]]:
    """Unique (layer, module) PRODUCT/HOOKS pairs. Layer names are discovered."""
    seen: set[str] = set()
    pairs: list[dict[str, str]] = []
    for leaf in discover_pycircuit_leaves() + discover_product_leaves():
        key = f"{leaf['layer']}/{leaf['module']}"
        if key in seen:
            continue
        seen.add(key)
        pairs.append(leaf)
    return pairs


PORT_CHUNK_RE = re.compile(
    r"\b(input|output|inout)\b((?:\s+(?:wire|reg|logic|signed))*"
    r"(?:\s+\[[^\]]+\])?\s*"
    r"[A-Za-z_][A-Za-z0-9_]*(?:\s*,\s*[A-Za-z_][A-Za-z0-9_]*)*)",
    re.I,
)
PORT_IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


_MODULE_DECL_RE = re.compile(r"^\s*module\s+([A-Za-z_][A-Za-z0-9_]*)\b", re.M)


def declared_module_name(text: str) -> str | None:
    m = _MODULE_DECL_RE.search(text)
    return m.group(1) if m else None


def verilog_equal_except_module_name(left: Path, right: Path) -> bool:
    """True if the two netlists match after substituting the declared module name."""
    ta = left.read_text(encoding="utf-8", errors="replace")
    tb = right.read_text(encoding="utf-8", errors="replace")
    na, nb = declared_module_name(ta), declared_module_name(tb)
    if not na or not nb:
        return ta == tb
    token = "__GATE_MOD__"

    def norm(text: str, name: str) -> str:
        return re.sub(rf"\b{re.escape(name)}\b", token, text)

    return norm(ta, na) == norm(tb, nb)


def collect_layer_netlists(rtl_root: Path) -> dict[str, Path]:
    """rtl/<layer>/*.v and rtl/<layer>/hooks/*.v, keyed by layer-relative path."""
    out: dict[str, Path] = {}
    if not rtl_root.is_dir():
        return out
    for layer_dir in sorted(rtl_root.iterdir()):
        if not layer_dir.is_dir():
            continue
        if layer_dir.name in LAYER_SKIP or layer_dir.name == "gen":
            continue
        for path in sorted(layer_dir.iterdir()):
            if path.is_file() and path.suffix.lower() in RTL_SOURCE_SUFFIXES:
                out[f"{layer_dir.name}/{path.name}"] = path
        hooks = layer_dir / "hooks"
        if hooks.is_dir():
            for path in sorted(hooks.iterdir()):
                if path.is_file() and path.suffix.lower() in RTL_SOURCE_SUFFIXES:
                    out[f"{layer_dir.name}/hooks/{path.name}"] = path
    return out


def parse_ports(path: Path) -> list[tuple[str, str]]:
    """Return (direction, name) in declaration order."""
    text = strip_verilog_comments(path.read_text(encoding="utf-8", errors="replace"))
    skip = {"input", "output", "inout", "wire", "reg", "logic", "signed"}
    ports: list[tuple[str, str]] = []
    for kind, blob in PORT_CHUNK_RE.findall(text):
        for name in PORT_IDENT_RE.findall(blob):
            if name.lower() in skip:
                continue
            ports.append((kind.lower(), name))
    return ports


def collect_blackbox_findings(check: str = "lint") -> list[Finding]:
    """Unlisted stub/macro is blocking. Timing vs MODULE_INVENTORY is report-only."""
    findings: list[Finding] = validate_blackbox_schema()
    for f in findings:
        f.check = check
    inventory = load_module_inventory()
    inv_path = find_module_inventory()
    storage_rows: list[dict[str, Any]] = []
    if inventory:
        raw = inventory.get("storage") or inventory.get("memories") or []
        if isinstance(raw, list):
            storage_rows = [r for r in raw if isinstance(r, dict)]
    if inv_path is None:
        print(
            "NOTE: MODULE_INVENTORY not found "
            "(docs/arch/MODULE_INVENTORY.yml); blackbox timing auto-check skipped"
        )
    listed = load_blackboxes()
    print(
        f"blackbox registry: {len(listed)} approved stub|macro entries "
        f"(ub_cmn_mem_1r1w is a normal cmn leaf, not listed here)"
    )
    for path in iter_rtl_sources():
        if is_handwritten_path(path):
            continue
        # Generated cmn storage leaf is a normal PRODUCT, not a stub.
        if path.stem == "ub_cmn_mem_1r1w" and "cmn" in path.parts:
            continue
        detected = looks_like_stub_or_blackbox(path)
        listed_here = is_stub_listed(path)
        if detected and not listed_here:
            findings.append(
                Finding(
                    check=check,
                    module=path.stem,
                    file=rel(path),
                    rule="STUB_UNLISTED",
                    message=(
                        "stub/blackbox under rtl/ is not on "
                        "scripts/gate/blackbox.yml "
                        "(or the entry has no gatekeeper approver)"
                    ),
                )
            )
            continue
        if not listed_here:
            continue
        entry = next(
            (
                e
                for e in listed
                if str(e.get("file") or "").replace("\\", "/") == rel(path)
                or fnmatch.fnmatch(rel(path), str(e.get("file") or ""))
                or str(e.get("module") or "") == path.stem
            ),
            {},
        )
        if not storage_rows:
            continue
        match = None
        for row in storage_rows:
            rid = str(row.get("id") or row.get("replaces") or row.get("macro") or "")
            rmod = str(row.get("module") or "")
            if rid and rid == str(entry.get("replaces") or entry.get("macro") or entry.get("id") or ""):
                match = row
                break
            if rmod and rmod in {path.stem, entry.get("module")}:
                match = row
                break
        if match is None:
            findings.append(
                Finding(
                    check=check,
                    module=path.stem,
                    file=rel(path),
                    rule="STUB_TIMING_NO_INVENTORY_ROW",
                    message=(
                        "registered stub/macro has no MODULE_INVENTORY storage row "
                        "to check read latency / 1RW/1R1W / conflict"
                    ),
                    bucket="report",
                )
            )
            continue
        want = {
            "read_latency": match.get("read_latency", match.get("read_lat")),
            "ports": match.get("ports") or match.get("port_kind"),
            "conflict": match.get("conflict")
            or match.get("rw_conflict")
            or match.get("same_addr"),
        }
        got = {
            "read_latency": entry.get("read_latency", entry.get("read_lat")),
            "ports": entry.get("ports") or entry.get("port_kind"),
            "conflict": entry.get("rw_conflict") or entry.get("conflict"),
        }
        mismatches = [
            f"{k}: inventory={want[k]!r} list={got[k]!r}"
            for k in want
            if want[k] is not None and got[k] is not None and str(want[k]) != str(got[k])
        ]
        missing = [k for k in want if want[k] is not None and got[k] is None]
        if mismatches or missing:
            findings.append(
                Finding(
                    check=check,
                    module=path.stem,
                    file=rel(path),
                    rule="STUB_TIMING",
                    message=(
                        "blackbox timing vs MODULE_INVENTORY (report-only): "
                        + "; ".join(mismatches + [f"{k} missing on list" for k in missing])
                    ),
                    bucket="report",
                )
            )
    return findings


def collect_stub_findings(check: str = "lint") -> list[Finding]:
    return collect_blackbox_findings(check)


def discover_product_leaves() -> list[dict[str, Any]]:
    """PRODUCT files at rtl/<layer>/<module>.v (not hooks/, not whitelist cells)."""
    rtl_root = REPO_ROOT / "rtl"
    leaves: list[dict[str, Any]] = []
    for layer in discover_layers(rtl_root):
        layer_dir = rtl_root / layer
        if not layer_dir.is_dir():
            continue
        for path in sorted(layer_dir.iterdir()):
            if not path.is_file() or path.suffix.lower() not in RTL_SOURCE_SUFFIXES:
                continue
            if is_handwritten_path(path) or path.stem in handwritten_modules():
                continue
            tag = None
            leaf_name = path.stem
            params: dict[str, Any] = {}
            cmn_tag = cmn_mem_tag_of(path.stem)
            if cmn_tag:
                leaf_name = CMN_MEM_CELL
                tag = cmn_tag
                params = parse_cmn_mem_tag(cmn_tag) or {}
            leaves.append(
                {
                    "layer": layer,
                    "leaf": leaf_name,
                    "module": path.stem,
                    "tag": tag,
                    "params": params,
                    "placeholder": is_placeholder_path(path),
                    "product": rel(path),
                    "hooks": f"rtl/{layer}/hooks/{path.stem}.v",
                }
            )
    return leaves


def module_closure(module: str, disc: dict) -> list[Path]:
    """Files needed to lint/synth `module` (itself + discovered children)."""
    defined: dict[str, RtlUnit] = disc.get("defined") or {}
    inst_map: dict[str, set[str]] = disc.get("instantiations") or {}
    seen: set[str] = set()
    stack = [module]
    files: list[Path] = []
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        seen.add(name)
        unit = defined.get(name)
        if unit is None:
            continue
        files.append(unit.file)
        for child in inst_map.get(name, set()):
            if child in defined:
                stack.append(child)
    return files


def strip_verilog_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out: list[str] = []
    for line in text.splitlines():
        if "//" in line:
            line = line.split("//", 1)[0]
        out.append(line)
    return "\n".join(out)


def verilator_inc_args(incdirs: list[Path]) -> list[str]:
    # Verilator treats a bare "-I" plus a following path as another source file.
    return [f"-I{d}" for d in incdirs]


def yosys_inc_prefix(incdirs: list[Path]) -> str:
    return " ".join(f"-I{d}" for d in incdirs)

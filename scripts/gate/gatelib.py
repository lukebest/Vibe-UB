def hooks_extra_for(module: str, leaf: str | None = None) -> list[str] | None:
    """Look up extra ports by variant module, then by untagged leaf."""
    table = load_hooks_ports()
    if module in table:
        return table[module]
    if leaf and leaf in table:
        return table[leaf]
    cmn_tag = cmn_mem_tag_of(module)
    if cmn_tag and CMN_MEM_CELL in table:
        return table[CMN_MEM_CELL]
    # ub_lmsm_x4 → ub_lmsm
    if "_" in module:
        stem = module.rsplit("_", 1)[0]
        if stem in table:
            return table[stem]
    return None



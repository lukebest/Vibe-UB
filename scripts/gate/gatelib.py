def load_waivers(check: str | None = None) -> list[dict[str, Any]]:
    approvers = load_approvers()
    accepted: list[dict[str, Any]] = []
    if not WAIVERS_DIR.is_dir():
        return accepted
    for path in sorted(WAIVERS_DIR.glob("*.yml")):
        if path.name == "approvers.yml":
            continue
        data = load_yaml(path)
        for entry in data.get("waivers") or []:
            if check and entry.get("check") != check:
                continue
            approver = str(entry.get("approver") or "").strip()
            status = str(entry.get("status") or "approved").strip().lower()
            if approver.lower() in PLACEHOLDER_APPROVERS:
                print(
                    f"WAIVER ignore {entry.get('id')}: no approver "
                    f"(待守门人批准)"
                )
                continue
            if approver not in approvers:
                print(
                    f"WAIVER ignore {entry.get('id')}: approver {approver!r} "
                    f"is not a verification gatekeeper"
                )
                continue
            if status in {"draft", "pending", "todo"}:
                print(f"WAIVER ignore {entry.get('id')}: status={status}")
                continue
            accepted.append(dict(entry))
    return accepted


def waiver_matches(finding: Finding, entry: dict[str, Any]) -> bool:
    if entry.get("check") and entry["check"] != finding.check:
        return False
    module = entry.get("module") or entry.get("模块")
    if module and str(module) not in {finding.module, "*"}:
        return False
    fpat = entry.get("file") or entry.get("文件")
    if fpat and not fnmatch.fnmatch(finding.file, str(fpat)):
        return False
    rule = entry.get("rule") or entry.get("规则")
    if rule and str(rule) not in {finding.rule, "*"}:
        return False
    msg = entry.get("message") or entry.get("消息匹配")
    if msg and not re.search(str(msg), finding.message):
        return False
    return True


def apply_waivers(findings: list[Finding], check: str) -> list[Finding]:
    waivers = load_waivers(check)
    for finding in findings:
        classify_finding(finding)
        for entry in waivers:
            if waiver_matches(finding, entry):
                finding.waived_by = str(entry.get("id") or entry.get("approver"))
                break
    return findings


def split_findings(
    findings: list[Finding],
) -> tuple[list[Finding], list[Finding], list[Finding], list[Finding], list[Finding]]:
    blocking: list[Finding] = []
    legacy: list[Finding] = []
    migrate: list[Finding] = []
    report: list[Finding] = []
    waived: list[Finding] = []
    for f in findings:
        if f.waived_by:
            waived.append(f)
        elif f.bucket == "legacy":
            legacy.append(f)
        elif f.bucket == "migrate":
            migrate.append(f)
        elif f.bucket == "report":
            report.append(f)
        else:
            blocking.append(f)
    return blocking, legacy, migrate, report, waived



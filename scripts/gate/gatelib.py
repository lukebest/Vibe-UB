def find_extra_toolchain_locks() -> list[Path]:
    """Any TOOLCHAIN.lock other than the repo-root copy is a conflict."""
    extras: list[Path] = []
    root = TOOLCHAIN_LOCK.resolve() if TOOLCHAIN_LOCK.is_file() else TOOLCHAIN_LOCK
    stack = [REPO_ROOT]
    while stack:
        d = stack.pop()
        try:
            kids = list(d.iterdir())
        except OSError:
            continue
        for child in kids:
            if child.is_dir():
                if child.name in LOCK_SCAN_SKIP_DIRS:
                    continue
                stack.append(child)
            elif child.name == "TOOLCHAIN.lock":
                try:
                    if child.resolve() != root:
                        extras.append(child)
                except OSError:
                    extras.append(child)
    return extras


def collect_toolchain_lock_findings(check: str) -> list[Finding]:
    extras = find_extra_toolchain_locks()
    if not extras:
        return []
    return [
        Finding(
            check=check,
            module="*",
            file="TOOLCHAIN.lock",
            rule="TOOLCHAIN_LOCK_CONFLICT",
            message=(
                "tool versions must come from the repo-root TOOLCHAIN.lock only; "
                f"extra copies: {[rel(p) for p in extras]}"
            ),
        )
    ]


def parse_lock(path: Path = TOOLCHAIN_LOCK) -> dict[str, str]:
    """Read the repo-root TOOLCHAIN.lock only. A second copy is a conflict."""
    if path.resolve() != TOOLCHAIN_LOCK.resolve():
        print(
            f"NOTE: ignoring non-root lock {rel(path)}; "
            f"versions from {rel(TOOLCHAIN_LOCK)} only"
        )
        path = TOOLCHAIN_LOCK
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("[") or "=" not in line:
            continue
        key, _, rest = line.partition("=")
        val = rest.strip().strip('"').strip("'")
        out[key.strip()] = val
    return out


def run_cmd(
    argv: list[str],
    cwd: Path | None = None,
    timeout: int | None = None,
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        argv,
        cwd=cwd or REPO_ROOT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        timeout=timeout,
        check=False,
    )


def tool_version_line(cmd: list[str], fallback: str = "not-on-PATH") -> str:
    if not shutil_which(cmd[0]):
        return fallback
    proc = run_cmd(cmd)
    text = (proc.stdout or "").strip().splitlines()
    return text[0] if text else fallback


def shutil_which(name: str) -> str | None:
    from shutil import which

    return which(name)


def print_tool_versions(needed: Iterable[str]) -> None:
    lock = parse_lock()
    mapping = {
        "verilator": ("verilator_lock", ["verilator", "--version"]),
        "icarus": ("icarus_lock", ["iverilog", "-V"]),
        "yosys": ("yosys_lock", ["yosys", "-V"]),
        "eqy": ("eqy_lock", ["eqy", "--version"]),
        "sby": ("sby_lock", ["sby", "--version"]),
        "pycc": ("llvm_lock", ["pycc", "--version"]),
        "python": ("python_lock", [sys.executable, "--version"]),
        "llvm": ("llvm_lock", ["llvm-config-19", "--version"]),
        "cmake": ("cmake_lock", ["cmake", "--version"]),
        "ninja": ("ninja_lock", ["ninja", "--version"]),
    }
    extras = find_extra_toolchain_locks()
    print("=== tool versions (repo-root TOOLCHAIN.lock vs actual) ===")
    if extras:
        print(
            "TOOLCHAIN.lock CONFLICT: extra copies "
            f"{[rel(p) for p in extras]} (root is the only allowed source)"
        )
    for name in needed:
        lock_key, argv = mapping[name]
        locked = lock.get(lock_key, "")
        actual = tool_version_line(argv)
        on_path = shutil_which(argv[0]) is not None
        if locked:
            matched = locked in actual
            status = "MATCH" if matched else "MISMATCH — locked version not installed; using actual (not silent)"
            print(f"TOOL {name}: locked={locked} actual={actual} {status}")
        else:
            extra = "locked=(not in TOOLCHAIN.lock)"
            print(f"TOOL {name}: {extra} actual={actual}")
        if name in {"verilator", "icarus", "yosys", "eqy"} and not on_path:
            print(f"TOOL {name}: MISSING on PATH")
    print("=== end tool versions ===")


def read_list_patterns(path: Path) -> list[str]:
    pats: list[str] = []
    if not path.is_file():
        return pats
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            pats.append(line.replace("\\", "/"))
    return pats


def read_legacy_patterns(path: Path = LEGACY_LIST) -> list[str]:
    return read_list_patterns(path)


def read_migrate_patterns(path: Path = MIGRATE_LIST) -> list[str]:
    return read_list_patterns(path)


def is_migrate_path(path: Path, patterns: list[str] | None = None) -> bool:
    """Existing pyCircuit leaves from main / PR #5 / #7 / #11 / #12 (迁移待办)."""
    rel_path = rel(path)
    pats = patterns if patterns is not None else read_migrate_patterns()
    for pat in pats:
        if rel_path == pat or fnmatch.fnmatch(rel_path, pat):
            return True
        p = Path(pat)
        if len(p.parts) >= 3 and p.parts[0] == "pycircuit":
            layer, stem = p.parts[1], p.stem
            if rel_path in {
                f"rtl/{layer}/{stem}.v",
                f"rtl/{layer}/hooks/{stem}.v",
            }:
                return True
    return False


def looks_generated(path: Path) -> bool:
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:4000]
    except OSError:
        return False
    return bool(GENERATED_BANNER.search(head))


def is_legacy_path(path: Path, patterns: list[str] | None = None) -> bool:
    """D10 leftover: listed in legacy.txt and not a pyCircuit rewrite."""
    if looks_generated(path):
        return False
    if is_handwritten_path(path):
        return False
    rel_path = rel(path)
    pats = patterns if patterns is not None else read_legacy_patterns()
    for pat in pats:
        if rel_path == pat or rel_path.startswith(pat.rstrip("/") + "/"):
            return True
        if fnmatch.fnmatch(rel_path, pat):
            return True
    return False


def _file_for_class(path_text: str) -> str:
    # Verilator prints file:line[:col]; classify on the path only.
    cleaned = path_text.split(":")[0] if path_text else ""
    return cleaned


def classify_finding(finding: Finding) -> Finding:
    if finding.bucket == "report":
        return finding
    if finding.check == "spec_leak" or finding.rule in {
        "PLACEHOLDER_INSTANTIATED",
        "PLACEHOLDER_SOURCE_MISSING",
    }:
        finding.bucket = "new"
        return finding
    path = Path(REPO_ROOT / _file_for_class(finding.file))
    if is_handwritten_path(path):
        finding.bucket = "new"
    elif is_migrate_path(path):
        finding.bucket = "migrate"
    elif is_legacy_path(path):
        finding.bucket = "legacy"
    else:
        finding.bucket = "new"
    return finding


def load_approvers() -> set[str]:
    if not APPROVERS_FILE.is_file():
        return set()
    data = load_yaml(APPROVERS_FILE)
    names: set[str] = set()
    for row in data.get("gatekeepers") or []:
        login = str(row.get("login") or "").strip()
        role = str(row.get("role") or "").strip().lower()
        if login and role in {"verification", "verif", "gatekeeper", "工具守门"}:
            names.add(login)
        if login:
            # login is accepted only when marked as the verification gatekeeper
            if row.get("gatekeeper") is True or role:
                names.add(login)
    return names


def _entry_approved(entry: dict[str, Any], approvers: set[str], kind: str) -> bool:
    ident = entry.get("id") or entry.get("file")
    approver = str(entry.get("approver") or "").strip()
    status = str(entry.get("status") or "approved").strip().lower()
    if approver.lower() in PLACEHOLDER_APPROVERS:
        print(f"{kind} ignore {ident}: no approver (待守门人批准)")
        return False
    if approver not in approvers:
        print(f"{kind} ignore {ident}: approver {approver!r} is not a verification gatekeeper")
        return False
    if status in {"draft", "pending", "todo"}:
        print(f"{kind} ignore {ident}: status={status}")
        return False
    return True


_LIST_CACHE: dict[str, list[dict[str, Any]]] = {}


def _load_approved_list(path: Path, key: str, kind: str) -> list[dict[str, Any]]:
    cache_key = str(path)
    if cache_key in _LIST_CACHE:
        return _LIST_CACHE[cache_key]
    if not path.is_file():
        _LIST_CACHE[cache_key] = []
        return []
    data = load_yaml(path)
    approvers = load_approvers()
    accepted: list[dict[str, Any]] = []
    for entry in data.get(key) or []:
        if _entry_approved(entry, approvers, kind):
            accepted.append(dict(entry))
    _LIST_CACHE[cache_key] = accepted
    return accepted



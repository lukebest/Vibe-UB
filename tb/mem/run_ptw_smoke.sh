#!/usr/bin/env bash
# Directed PRODUCT smoke for ub_mem_ptw.
# Success cases swap in tb/mem/ub_mem_ptw_desc_dec_tb_model.v (TB protocol).
# Stub cases keep the public placeholder (always translation-fault).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
RTL="$ROOT/rtl/mem"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/ub_mem_ptw_smoke.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

PR21_REF="${PR21_REF:-origin/cursor/cmn-mem-1r1w-5d26}"
if [[ -f "$ROOT/rtl/pyc_lib/pyc_reg.v" ]]; then
  PYC_INC="$ROOT/rtl/pyc_lib"
else
  git -C "$ROOT" cat-file -e "${PR21_REF}:rtl/pyc_lib/pyc_reg.v" 2>/dev/null \
    || git -C "$ROOT" fetch origin cursor/cmn-mem-1r1w-5d26
  mkdir -p "$WORK/pyc_lib"
  git -C "$ROOT" show "${PR21_REF}:rtl/pyc_lib/pyc_reg.v" > "$WORK/pyc_lib/pyc_reg.v"
  PYC_INC="$WORK/pyc_lib"
fi
PYC_REG="$PYC_INC/pyc_reg.v"
if [[ ! -f "$PYC_REG" ]]; then
  echo "FAIL: pyc_reg.v not found (need #21 rtl/pyc_lib or fetch $PR21_REF)"
  exit 1
fi

# TODO: switch to scripts/gate/gen_private_stub.py once #47 is on main.
PY="${PY:-/tmp/spike/venv/bin/python3}"
if [[ ! -x "$PY" ]]; then
  PY=python3
fi
STUB_V="$WORK/ub_mem_ptw_desc_dec.v"
"$PY" "$ROOT/scripts/gen_ptw_desc_dec_stub.py" --out "$STUB_V"
grep -v '^`include "pyc_reg.v"' "$STUB_V" > "$WORK/stub_ninc.v"

python3 - "$RTL/ub_mem_ptw.v" "$WORK/ub_mem_ptw_stripped.v" <<'PY'
import sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
text = text.replace('`include "pyc_reg.v"\n\n', "", 1)
name = "ub_mem_ptw_desc_dec"
needle = f"module {name} ("
start = text.find(needle)
if start < 0:
    raise SystemExit("no embedded decoder module")
comm = text.rfind("// Generated by pycc", 0, start)
prev_end = text.rfind("endmodule", 0, start)
if comm >= 0 and comm > prev_end:
    start = comm
end = text.find("endmodule", start)
if end < 0:
    raise SystemExit("no endmodule for embedded decoder")
end = end + len("endmodule")
while end < len(text) and text[end] in "\r\n":
    end += 1
open(dst, "w", encoding="utf-8").write(text[:start] + text[end:])
print("stripped embedded decoder from parent")
PY

echo "=== functional smoke (TB decoder model) ==="
verilator --binary --timing --top-module ub_mem_ptw_smoke_tb \
  -Wno-DECLFILENAME -Wno-UNUSEDSIGNAL -Wno-UNDRIVEN -Wno-MODDUP -Wno-WIDTHTRUNC \
  -I"$PYC_INC" \
  "$PYC_REG" \
  "$WORK/ub_mem_ptw_stripped.v" \
  "$ROOT/tb/mem/ub_mem_ptw_desc_dec_tb_model.v" \
  "$ROOT/tb/mem/ub_mem_ptw_smoke_tb.v" \
  -Mdir "$WORK/obj_fn" \
  -o smoke_fn
"$WORK/obj_fn/smoke_fn"

echo "=== stub smoke (public placeholder) ==="
verilator --binary --timing --top-module ub_mem_ptw_stub_smoke_tb \
  -Wno-DECLFILENAME -Wno-UNUSEDSIGNAL -Wno-UNDRIVEN -Wno-MODDUP -Wno-WIDTHTRUNC \
  -I"$PYC_INC" \
  "$PYC_REG" \
  "$WORK/ub_mem_ptw_stripped.v" \
  "$WORK/stub_ninc.v" \
  "$ROOT/tb/mem/ub_mem_ptw_stub_smoke_tb.v" \
  -Mdir "$WORK/obj_stub" \
  -o smoke_stub
"$WORK/obj_stub/smoke_stub"

echo "PTW SMOKE DONE"
